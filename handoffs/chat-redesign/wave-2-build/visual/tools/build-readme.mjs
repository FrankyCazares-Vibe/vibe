// Builds the README table for handoffs/chat-redesign/wave-2-build/visual from
// the shooter's records (shots.json, unmocked.json, console.json) in OUT_DIR.
// Prints the Markdown table + the two lists to stdout; the README embeds it.

import fs from "node:fs";
import path from "node:path";

const OUT = path.resolve(process.env.OUT_DIR || "out");
const read = (f, def) => {
  try {
    return JSON.parse(fs.readFileSync(path.join(OUT, f), "utf8"));
  } catch {
    return def;
  }
};
const { shots, now } = read("shots.json", { shots: [], now: "" });
const unmocked = read("unmocked.json", []);
const consoleLog = read("console.json", []);

/** state → the mockup(s) it is checked against (Light shots against W0_Club_Light where one exists). */
const MOCKUP_FOR = {
  "01-home-all": ["W0_Home"],
  "02-home-chats": ["W0_Home"],
  "03-home-clubs": ["W0_Home"],
  "04-home-requests": [],
  "05-home-no-clubs": ["W0_EmptyClubs"],
  "06-home-empty-week": ["W0_EmptyWeek"],
  "07-club-lounge": ["W0_Club", "W0_Club_Light"],
  "08-club-lounge-full": ["W0_Club", "W0_Cards"],
  "09-board": ["W0_Board"],
  "10-board-fold-open": ["W0_Board"],
  "11-event-live": ["W0_Room"],
  "12-event-closed": ["W0_Room"],
  "13-event-after": ["W0_Room"],
  "14-tray": ["W0_Tray"],
  "15-new-poll-empty": ["W0_NewPoll"],
  "16-new-poll-filled": ["W0_NewPoll"],
  "17-new-signup": ["W0_NewSignup"],
  "18-share-event": ["W0_ShareEvent"],
  "19-share-event-empty": ["W0_ShareEvent"],
  "20-rsvp-sheet": [],
  "21-long-press-remove": [],
  "22-empty-club": ["W0_EmptyClub"],
  "23-load-failed": [],
  "24-skeleton": [],
  // run 2: the states the reviews listed as not shot
  "25-new-signup-empty": ["W0_NewSignup"],
  "26-remove-confirm": [],
  "27-member-board": ["W0_Board"],
  "28-member-lounge-picker": ["W0_Club"],
  "29-event-empty-soon": ["W0_Room"],
  "30-home-chats-empty": [],
  "31-home-requests-empty": [],
  "32-week-failed": [],
  "33-club-failed": [],
  "34-board-failed": [],
  "35-share-events-failed": ["W0_ShareEvent"],
  "36-flag-pending": [],
};

/** The layout viewport a shot was taken at: innerWidth/scrollWidth, `(clip)` when --clip-week was on. */
const layoutOf = (s) => (s?.layout ? `${s.layout.innerWidth}/${s.layout.scrollWidth}${s.clipWeek ? " (clip)" : ""}` : "");
const byState = new Map();
for (const s of shots) {
  if (s.theme === "mockup") continue;
  const row = byState.get(s.state) ?? { state: s.state, light: null, night: null, notes: [], layout: {} };
  if (s.file) row[s.theme] = s.file;
  if (s.file) row.layout[s.theme] = layoutOf(s);
  else row.notes.push(`${s.theme}: ${s.note}`);
  if (s.note && s.file && !row.notes.includes(s.note)) row.notes.push(s.note);
  byState.set(s.state, row);
}
const link = (f) => (f ? `[${f}](./${f})` : "—");
const lines = [];
lines.push("| # | state | app · Light | app · Night | layout L / N | mockup | notes |");
lines.push("|---|---|---|---|---|---|---|");
for (const name of Object.keys(MOCKUP_FOR)) {
  const row = byState.get(name) ?? { state: name, light: null, night: null, notes: ["not shot"] };
  const mocks = MOCKUP_FOR[name].map((m) => `[${m}](./mockup-${m}.png)`).join(", ") || "—";
  const num = name.slice(0, 2);
  const label = name.slice(3);
  const note = [...new Set(row.notes)].join(" · ").replace(/\|/g, "\\|");
  const lay = row.layout ? [row.layout.light, row.layout.night].filter(Boolean).join(" · ") : "";
  lines.push(`| ${num} | \`${label}\` | ${link(row.light)} | ${link(row.night)} | ${lay} | ${mocks} | ${note} |`);
}
const table = lines.join("\n");

const mockupFiles = shots.filter((s) => s.theme === "mockup").map((s) => `- [${s.file}](./${s.file}) — ${s.state}`);
// One line per distinct message, with how many states logged it (the full list is console.json).
const errors = consoleLog.filter((c) => c.kind !== "warning");
const counts = new Map();
for (const c of errors) {
  const key = c.text.split("\n")[0].slice(0, 140);
  const e = counts.get(key) ?? { n: 0, states: new Set() };
  e.n += 1;
  e.states.add(c.state || "(warm-up)");
  counts.set(key, e);
}
const errorLines = [...counts.entries()].map(([text, e]) => `${e.n}× (${e.states.size} state${e.states.size === 1 ? "" : "s"}): ${text}`);

process.stdout.write(
  [
    `<!-- generated by tools/build-readme.mjs from shots.json (NOW ${now}) -->`,
    table,
    "",
    "### Mockups (390 wide, full page)",
    mockupFiles.join("\n"),
    "",
    "### Unmocked /api calls seen",
    unmocked.length ? unmocked.map((u) => `- \`${u}\``).join("\n") : "- none: every call the screens made was in the fixture table.",
    "",
    "### Console errors while shooting",
    errorLines.length ? errorLines.map((l) => `- ${l}`).join("\n") : "- none",
    "",
  ].join("\n"),
);

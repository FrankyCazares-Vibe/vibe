// Pin a message inside the dm frame, open the Pinned and Shared panel, unpin. LOCAL stack only.
import { createRequire } from "node:module";
import { execSync } from "node:child_process";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.HOME + "/.claude/skills/gstack/node_modules/playwright-core");
const BASE = "http://localhost:3104";
const out = new URL("./", import.meta.url).pathname;
const raw = execSync("node handoffs/chat-redesign/wave-1-build/tools/cookie.mjs franky", { cwd: "/Users/franciscocazares/vibe", encoding: "utf8" });
const cookies = raw.split("; ").map((p) => { const i = p.indexOf("="); return { name: p.slice(0, i), value: p.slice(i + 1), domain: "localhost", path: "/" }; });
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: "dark" });
await ctx.addCookies(cookies);
const page = await ctx.newPage();
const net = [];
page.on("response", (r) => { const u = r.url(); if (/pin|shared/.test(u)) net.push(`${r.request().method()} ${r.status()} ${u.replace(BASE, "").slice(0, 110)}`); });
await page.goto(BASE + "/messages?channel=3560dfef-08d0-44ac-9138-7dc2b1afbbd0", { waitUntil: "domcontentloaded" });
await page.waitForTimeout(10000);
const frame = page.frames().find((f) => /messages\.html/.test(f.url()));
const info = await frame.evaluate(() => {
  const rows = [...document.querySelectorAll("[data-mid]")];
  const r = rows[rows.length - 2];
  const b = r.querySelector('button[aria-label="Pin message"]');
  const cs = b ? getComputedStyle(b) : null;
  const pill = b ? b.parentElement : null;
  const ps = pill ? getComputedStyle(pill) : null;
  return { mid: r.getAttribute("data-mid"), text: r.innerText.slice(0, 60), btn: !!b, display: cs && cs.display, vis: cs && cs.visibility, pillOpacity: ps && ps.opacity, pillDisplay: ps && ps.display, pillPE: ps && ps.pointerEvents, rect: b ? JSON.stringify(b.getBoundingClientRect()) : null };
});
console.log("pin button:", JSON.stringify(info));
const bubble = frame.locator(`[data-mid="${info.mid}"] .bubble, [data-mid="${info.mid}"] [class*=bubble]`).first();
await bubble.hover().catch((e) => console.log("hover failed:", String(e).split("\n")[0]));
await page.waitForTimeout(700);
await page.screenshot({ path: out + "w5-pin-hover.png" });
const pin = frame.locator(`[data-mid="${info.mid}"] button[aria-label="Pin message"]`).first();
await pin.click({ timeout: 4000 }).catch(async (e) => { console.log("normal click failed:", String(e).split("\n")[0].slice(0, 120), "-> trying a scripted click"); await frame.evaluate((mid) => document.querySelector(`[data-mid="${mid}"] button[aria-label="Pin message"]`).click(), info.mid); });
await page.waitForTimeout(2500);
await page.screenshot({ path: out + "w5-pinned-thread.png" });
await frame.locator('button[aria-label="Pinned and shared"]').first().click({ timeout: 5000 }).catch((e) => console.log("panel toggle failed:", String(e).split("\n")[0]));
await page.waitForTimeout(3000);
await page.screenshot({ path: out + "w5-pins-panel.png" });
console.log("panel text:", JSON.stringify(await page.evaluate(() => { const a = [...document.querySelectorAll("aside, section, div")].find((e) => /^Pinned/.test((e.innerText || "").trim()) && e.getBoundingClientRect().width < 340 && e.getBoundingClientRect().width > 200); return a ? a.innerText.slice(0, 500) : null; })));
console.log("unpin buttons in frame:", await frame.locator('button[aria-label="Unpin message"]').count());
console.log("net:\n  " + net.join("\n  "));
await browser.close();
